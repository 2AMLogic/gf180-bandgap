#!/usr/bin/env python3
"""Derive the tie-aware LVS reference from ``bandgap_top.ref.spice`` (gf180-bandgap#378).

``make_reference.py`` encodes the klt gf180mcu extraction deck *as it behaved
before klayout-tools#1084* (first released in klt 0.3.0): the deck could not
see well/substrate ties, so the reference carries

* ``vsubs``   -- the substrate global, a pin separate from ``vss``;
* ``nwl``     -- the PMOS band's Nwell, a floating net separate from ``vdd``;
* ``nw_<unit>`` -- each PNP unit's own Nwell (its base), floating.

From klt 0.3.0 on, the deck derives a tap region from the Nplus/Pplus implants
(n+ Comp inside Nwell = well tie, p+ Comp outside Nwell = substrate tie), so
the *same, unchanged* GDS extracts with ``vsubs`` and every ``nw_*`` base tied
to ``vss`` and ``nwl`` tied to ``vdd``. That is what ``design/netlist`` draws
(``XQn vss vss <emitter>``) and what the layout physically does; it is not a
short. Against the old-deck reference it reads as ten ``net.merged``.

This script applies exactly those three net aliases, nothing else, and drops
the now-redundant ``vsubs`` pin. Usage::

    python3 layout/lvs/tie_reference.py -o layout/lvs/bandgap_top.ref-tied.spice
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "bandgap_top.ref.spice"

_SUBCKT_OLD = ".SUBCKT bandgap_top vdd vss vref vsubs"
_SUBCKT_NEW = ".SUBCKT bandgap_top vdd vss vref"


def tie(text: str) -> str:
    """Return ``text`` with substrate/well nets aliased onto their rails."""
    if _SUBCKT_OLD not in text:
        raise ValueError(f"reference has no {_SUBCKT_OLD!r} line; not the old-deck shape")
    out = []
    for line in text.splitlines():
        if line.startswith("*"):
            out.append(line)
            continue
        line = line.replace(_SUBCKT_OLD, _SUBCKT_NEW)
        line = re.sub(r"\bvsubs\b", "vss", line)
        line = re.sub(r"\bnwl\b", "vdd", line)
        line = re.sub(r"\bnw_\w+", "vss", line)
        out.append(line)
    header = [
        "* TIE-AWARE variant of bandgap_top.ref.spice -- GENERATED by",
        "* layout/lvs/tie_reference.py (gf180-bandgap#378), do not edit.",
        "* vsubs -> vss, nwl -> vdd, nw_<unit> -> vss: the ties klt >= 0.3.0 recognises.",
    ]
    return "\n".join(header + out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("-o", "--output", type=Path, required=True)
    parser.add_argument("--source", type=Path, default=SOURCE)
    args = parser.parse_args()
    args.output.write_text(tie(args.source.read_text()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
